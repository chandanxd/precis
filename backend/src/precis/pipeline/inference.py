"""
Interacts with locally served Ollama instances using a strict QA prompt
template grounded in packed SVOA facts.

Supports configurable local LLMs, streaming token generation, blocking
responses, and inference performance telemetry.
"""

import json
import os
import re
import time
from collections.abc import Generator
from dataclasses import dataclass
from typing import Any, Literal, overload

import requests
from precis.pipeline.hardware import PRIMARY_MODEL


class ThinkBlockFilter:
    """Stateful filter to strip <think>...</think> reasoning blocks during token streaming."""
    def __init__(self):
        self.in_think = False
        self.buffer = ""

    def filter_token(self, token: str) -> str:
        self.buffer += token
        output = ""
        while True:
            if not self.in_think:
                start_idx = self.buffer.find("<think>")
                if start_idx != -1:
                    output += self.buffer[:start_idx]
                    self.buffer = self.buffer[start_idx + len("<think>"):]
                    self.in_think = True
                else:
                    partial_match = False
                    for i in range(1, len("<think>")):
                        if self.buffer.endswith("<think>"[:i]):
                            output += self.buffer[:-i]
                            self.buffer = self.buffer[-i:]
                            partial_match = True
                            break
                    if not partial_match:
                        output += self.buffer
                        self.buffer = ""
                    break
            else:
                end_idx = self.buffer.find("</think>")
                if end_idx != -1:
                    self.buffer = self.buffer[end_idx + len("</think>"):]
                    self.in_think = False
                else:
                    partial_match = False
                    for i in range(1, len("</think>")):
                        if self.buffer.endswith("</think>"[:i]):
                            self.buffer = self.buffer[-i:]
                            partial_match = True
                            break
                    if not partial_match:
                        self.buffer = ""
                    break
        return output

    def flush(self) -> str:
        """Flush any remaining buffer at end of stream, stripping any unclosed think tags."""
        remaining = self.buffer
        self.buffer = ""
        self.in_think = False
        cleaned = re.sub(r"</?think>", "", remaining, flags=re.DOTALL).strip()
        return cleaned


def strip_thinking_tags(text: str) -> str:
    """Remove <think>...</think> reasoning blocks generated by reasoning models.
    If the model output was entirely inside <think> (or cut off), extract the conclusion/last lines of the reasoning.
    """
    if not text:
        return ""
    cleaned = re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL)
    # An unterminated <think> (output cut off) must not leak its reasoning
    # after a real answer.
    cleaned = re.sub(r"<think>.*$", "", cleaned, flags=re.DOTALL).strip()
    if cleaned:
        return cleaned
    inner = text.replace("<think>", "").replace("</think>", "").strip()
    if inner:
        paragraphs = [p.strip() for p in inner.split("\n\n") if p.strip()]
        if paragraphs:
            return paragraphs[-1]
        return inner
    return text.strip()


