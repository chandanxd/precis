def generate_answer(
    query: str,
    context: str = "",
    model: str | None = None,
    stream: bool = False,
    base_url: str = OLLAMA_DEFAULT_BASE_URL,
    temperature: float = 0.3,
    top_p: float = 0.9,
    max_tokens: int = 2048,
    prompt_style: Literal["standard", "concise"] | None = None,
    prompt_type: Literal["grounded", "conversational", "document_chat"] = "grounded",
    history: list[Any] | None = None,
) -> InferenceResult | Generator[str, None, InferenceResult]:
    """
    Generate an answer using local Ollama LLM.

    Args:
        query: User question.
        context: Packed context from Stage 4 (for grounded QA).
        model: Model identifier in Ollama.
        stream: If True, yields tokens one at a time and returns InferenceResult.
        base_url: Ollama API base URL.
        temperature: Sampling temperature.
        top_p: Nucleus sampling probability.
        max_tokens: Maximum tokens to generate.
        prompt_style: "standard" or "concise" prompt template style.
        prompt_type: "grounded" (default; the evaluated strict prompt),
            "conversational", or "document_chat" (chat app: facts plus history,
            with a labelled general-knowledge fallback).
        history: Optional conversation history for the conversational and
            document_chat prompts.

    Returns:
        InferenceResult or generator yielding tokens with final InferenceResult.
    """
    if model is None:
        model = os.getenv(
            "PRECIS_OLLAMA_MODEL",
            PRIMARY_MODEL,
        )

    if not 0.0 <= temperature <= 2.0:
        raise ValueError("temperature must be between 0.0 and 2.0")

    if not 0.0 < top_p <= 1.0:
        raise ValueError("top_p must be between 0.0 and 1.0")

    if max_tokens <= 0:
        raise ValueError("max_tokens must be greater than 0")

    base_url = base_url.rstrip("/")
    endpoint = f"{base_url}/api/generate"
    if prompt_type == "conversational":
        prompt = build_conversational_prompt(query, history=history)
    elif prompt_type == "document_chat":
        prompt = build_document_chat_prompt(context, query, history=history)
    else:
        prompt = build_prompt(context, query, prompt_style=prompt_style)

    payload: dict[str, Any] = {
        "model": model,
        "prompt": prompt,
        "stream": stream,
        "options": {
            "temperature": temperature,
            "top_p": top_p,
            "num_predict": max_tokens,
            "num_ctx": _context_window(prompt, max_tokens),
        },
    }
    if prompt_type != "grounded":
        # Thinking models (qwen3.5) otherwise spend most of the token budget
        # reasoning before a chat reply and can return nothing. The evaluated
        # grounded prompt keeps Ollama's default so experiments are unchanged.
        payload["think"] = False

    start_time = time.perf_counter()

    if stream:

        def stream_generator() -> Generator[str, None, InferenceResult]:
            tokens: list[str] = []
            gen = _stream_ollama(endpoint, payload)

            try:
                while True:
                    tok = next(gen)
                    tokens.append(tok)
                    yield tok
            except GeneratorExit:
                gen.close()
                raise
            except StopIteration as exc:
                full_text, eval_cnt, prompt_cnt = (
                    exc.value
                    if exc.value
                    else (
                        "".join(tokens),
                        len(tokens),
                        0,
                    )
                )

                elapsed = int((time.perf_counter() - start_time) * 1000)

                return InferenceResult(
                    answer=full_text,
                    model=model,
                    latency_ms=elapsed,
                    tokens_generated=eval_cnt or len(tokens),
                    prompt_tokens=prompt_cnt,
                )

        return stream_generator()

    try:
        resp = requests.post(
            endpoint,
            json=payload,
            timeout=120,
        )
        resp.raise_for_status()
        data = resp.json()

    except ValueError as exc:
        raise OllamaInferenceError(
            "Ollama returned a malformed response"
        ) from exc
    except requests.ConnectionError as exc:
        raise OllamaConnectionError(
            f"Could not connect to Ollama at {base_url}"
        ) from exc
    except requests.RequestException as exc:
        raise OllamaInferenceError(f"Ollama inference request failed: {exc}") from exc

    elapsed_ms = int((time.perf_counter() - start_time) * 1000)

    answer = strip_thinking_tags(data.get("response", ""))
    tokens_generated = data.get(
        "eval_count",
        len(answer.split()),
    )
    prompt_tokens = data.get(
        "prompt_eval_count",
        0,
    )

    return InferenceResult(
        answer=answer,
        model=model,
        latency_ms=elapsed_ms,
        tokens_generated=tokens_generated,
        prompt_tokens=prompt_tokens,
    )
