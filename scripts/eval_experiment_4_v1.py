def estimate_text_tokens(text: str) -> int:
    """
    Standard subword heuristic estimator used across Précis evaluation harnesses:
    int(len(text.split()) * 1.3).
    MUST be recorded as 'context_estimated_tokens' and NOT conflated with actual model tokens.
    """
    words = len(text.split())
    return int(words * 1.3)


