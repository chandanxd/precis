def main():
    args = parse_args()
    print("=" * 80)
    print(f"PRECIS EXPERIMENT 4: CONTROLLED GENERATION PILOT ({EXPERIMENT_ID})")
    print(f"Mode: {'DRY RUN (ZERO INFERENCE)' if args.dry_run else 'LIVE GENERATION'}")
    print("=" * 80)

    # 1. Load inputs
    manifest_path = REPO_ROOT / "results/diagnostic_structural_decompilation_v3/sample_manifest.jsonl"
    stage_c_path = REPO_ROOT / "results/diagnostic_structural_decompilation_v3/eval_records_stage_c.jsonl"
    dataset_path = REPO_ROOT / "backend/data/nq_subset/nq_dev.jsonl"

    print("Verifying input provenance...")
    input_hashes = {
        "manifest": compute_sha256(manifest_path),
        "stage_c_records": compute_sha256(stage_c_path),
        "dataset": compute_sha256(dataset_path),
    }
    for k, v in input_hashes.items():
        print(f"  {k:<20}: {v}")

    with open(manifest_path, "r", encoding="utf-8") as f:
        manifest_records = [json.loads(line) for line in f if line.strip()]

    with open(dataset_path, "r", encoding="utf-8") as f:
        dataset_docs = {json.loads(line)["doc_id"]: json.loads(line) for line in f if line.strip()}

    # Load frozen Stage C records for all cases
    all_target_cids = {
        m["sample_id"] for m in manifest_records
        if m.get("type") == "sample_record" and m.get("stratum") == "table_bearing"
    }
    frozen_stage_c = load_frozen_baseline_records(stage_c_path, all_target_cids)

    # Reconstruct 58-case union
    regressions, recoveries, union_cases = validate_cohort_membership(manifest_records, frozen_stage_c)
    print(f"\nCohort Reconstructed:")
    print(f"  Confirmatory table stratum: {len(all_target_cids)} cases")
    print(f"  Stage C regressions (P1):  {len(regressions)} cases")
    print(f"  Stage C recoveries (P2):   {len(recoveries)} cases")
    print(f"  Targeted unique union:     {len(union_cases)} cases")

    # Select cases to run
    if args.cases:
        selected_cases = [c.strip() for c in args.cases.split(",") if c.strip()]
    elif args.smoke_test:
        selected_cases = list(SMOKE_TEST_CASE_IDS)
    else:
        selected_cases = union_cases

    print(f"Evaluating {len(selected_cases)} cases...")

    # Fingerprint
    fingerprint = compute_configuration_fingerprint(
        model=args.model,
        temperature=args.temperature,
        top_p=args.top_p,
        seed=args.seed,
        max_tokens=args.max_tokens,
        token_ceiling=args.token_ceiling,
        input_hashes=input_hashes,
    )
    print(f"Configuration Fingerprint: {fingerprint}")

    summary = run_experiment_4(
        target_case_ids=selected_cases,
        manifest_records=manifest_records,
        dataset_docs=dataset_docs,
        frozen_stage_c=frozen_stage_c,
        output_dir=args.output_dir,
        dry_run=args.dry_run,
        force=args.force,
        model=args.model,
        temperature=args.temperature,
        top_p=args.top_p,
        seed=args.seed,
        max_tokens=args.max_tokens,
        token_ceiling=args.token_ceiling,
    )
    print("\nRun Complete. Condition Summaries:")
    print(json.dumps(summary["condition_summaries"], indent=2))


if __name__ == "__main__":
    main()
