REWRITE_PROMPT_TEMPLATE = """Rewrite the user's last message as one standalone question that can be understood without the conversation. Replace pronouns and references such as "it", "they", "that year" with what they refer to. Keep names, numbers and dates. If the message is already standalone, repeat it unchanged. Output only the question.

{history_section}LAST MESSAGE:
{query}

STANDALONE QUESTION:"""

# Long grounded answers are cut in the prompt's history so that a few turns do
# not crowd out the packed facts.
HISTORY_TURN_MAX_CHARS = 1000


class OllamaConnectionError(Exception):
    """Raised when the local Ollama instance cannot be reached."""


class OllamaInferenceError(Exception):
    """Raised when Ollama fails to generate a response."""


@dataclass
class InferenceResult:
    """Result and performance telemetry from local LLM inference."""

    answer: str
    model: str
    latency_ms: int
    tokens_generated: int
    prompt_tokens: int = 0


def check_ollama(base_url: str = OLLAMA_DEFAULT_BASE_URL) -> bool:
    """Check if the local Ollama daemon is running and reachable."""
    try:
        resp = requests.get(f"{base_url}/api/tags", timeout=3)
        return resp.status_code == 200
    except (requests.ConnectionError, requests.Timeout):
        return False


def build_prompt(
    context: str,
    query: str,
    prompt_style: Literal["standard", "concise"] | None = None,
) -> str:
    """Format the grounded QA prompt from packed facts and user query.

    Args:
        context: Rendered facts from Stage 4.
        query: User question.
        prompt_style: "standard" (default conversational QA) or "concise"
            (tested brevity format for extractive answer alignment).
            Defaults to the PRECIS_PROMPT_STYLE environment variable if set,
            otherwise "standard".
    """
    clean_query = query.strip()

    if not clean_query:
        raise ValueError("Query must not be empty.")

    clean_context = (
        context.strip()
        if context and context.strip()
        else "(No relevant facts retrieved)"
    )

    style = (prompt_style or os.getenv("PRECIS_PROMPT_STYLE", "standard")).lower()
    template = (
        CONCISE_PROMPT_TEMPLATE
        if style == "concise"
        else STANDARD_PROMPT_TEMPLATE
    )

    return template.format(
        context=clean_context,
        query=clean_query,
    )


def build_conversational_prompt(
    query: str,
    history: list[Any] | None = None,
) -> str:
    """Format an ungrounded conversational prompt for casual conversation.

    Args:
        query: User message.
        history: Optional sequence of ChatMessage objects or dicts with role and content.
    """
    clean_query = query.strip()
    if not clean_query:
        raise ValueError("Query must not be empty.")

    return CONVERSATIONAL_PROMPT_TEMPLATE.format(
        history_section=_render_history(history),
        query=clean_query,
    )


def build_document_chat_prompt(
    context: str,
    query: str,
    history: list[Any] | None = None,
) -> str:
    """Format the chat-app prompt for document questions: packed facts plus
    conversation history, with a labelled fallback to general knowledge."""
    clean_query = query.strip()
    if not clean_query:
        raise ValueError("Query must not be empty.")

    clean_context = (
        context.strip()
        if context and context.strip()
        else "(No relevant facts retrieved)"
    )

    return DOCUMENT_CHAT_PROMPT_TEMPLATE.format(
        history_section=_render_history(history),
        context=clean_context,
        query=clean_query,
    )


def _render_history(history: list[Any] | None) -> str:
    """Render ChatMessage objects or role/content dicts as a prompt section."""
    if not history:
        return ""
    lines: list[str] = ["CONVERSATION HISTORY:"]
    for turn in history:
        role = getattr(turn, "role", None) or (turn.get("role") if isinstance(turn, dict) else "user")
        content = getattr(turn, "content", None) or (turn.get("content") if isinstance(turn, dict) else str(turn))
        content = str(content)
        if len(content) > HISTORY_TURN_MAX_CHARS:
            content = content[:HISTORY_TURN_MAX_CHARS].rstrip() + " …"
        prefix = "User" if str(role).lower() == "user" else "Assistant"
        lines.append(f"{prefix}: {content}")
    lines.append("")
    return "\n".join(lines) + "\n"


def rewrite_followup_query(
    query: str,
    history: list[Any],
    model: str | None = None,
    base_url: str = OLLAMA_DEFAULT_BASE_URL,
) -> str:
    """Ask the local model to turn a follow-up into a standalone question.

    Raises OllamaConnectionError / OllamaInferenceError like generate_answer;
    returns the original query when the model's output is unusable.
    """
    if model is None:
        model = os.getenv("PRECIS_OLLAMA_MODEL", PRIMARY_MODEL)

    prompt = REWRITE_PROMPT_TEMPLATE.format(
        history_section=_render_history(history),
        query=query.strip(),
    )
    payload = {
        "model": model,
        "prompt": prompt,
        "stream": False,
        "think": False,
        "options": {
            "temperature": 0.0,
            "num_predict": 96,
            "num_ctx": _context_window(prompt, 96),
        },
    }
    try:
        resp = requests.post(f"{base_url.rstrip('/')}/api/generate", json=payload, timeout=60)
        resp.raise_for_status()
        data = resp.json()
    except ValueError as exc:
        raise OllamaInferenceError("Ollama returned a malformed response") from exc
    except requests.ConnectionError as exc:
        raise OllamaConnectionError(f"Could not connect to Ollama at {base_url}") from exc
    except requests.RequestException as exc:
        raise OllamaInferenceError(f"Ollama rewrite request failed: {exc}") from exc

    lines = [ln.strip() for ln in strip_thinking_tags(data.get("response", "")).splitlines() if ln.strip()]
    rewritten = lines[0].strip(" \"'`") if lines else ""
    if rewritten.lower().startswith("standalone question:"):
        rewritten = rewritten.split(":", 1)[1].strip(" \"'`")
    if not rewritten or len(rewritten) > 3 * len(query) + 200:
        return query
    return rewritten


def _context_window(prompt: str, max_tokens: int) -> int:
    """Context window to request from Ollama so the prompt is never truncated.

    Ollama's default window can be smaller than the packed context plus the
    template, question and generation budget. Rounded up to 1024 so the loaded
    model is not reloaded on every request.
    """
    override = os.getenv("PRECIS_NUM_CTX")
    if override and override.isdigit():
        return int(override)
    estimated = len(prompt) // 3 + max_tokens + 256  # conservative chars->tokens
    rounded = ((estimated + 1023) // 1024) * 1024
    return max(4096, min(rounded, 32768))


def _stream_ollama(
    endpoint: str,
    payload: dict[str, Any],
) -> Generator[str, None, tuple[str, int, int]]:
    """Stream tokens from Ollama, returning
    (full_answer, eval_count, prompt_eval_count).
    """
    full_answer: list[str] = []
    eval_count = 0
    prompt_eval_count = 0
    think_filter = ThinkBlockFilter()

    try:
        resp = requests.post(
            endpoint,
            json=payload,
            stream=True,
            timeout=120,
        )
        resp.raise_for_status()
    except requests.ConnectionError as exc:
        raise OllamaConnectionError(
            f"Could not connect to Ollama at {endpoint}"
        ) from exc
    except requests.RequestException as exc:
        raise OllamaInferenceError(f"Ollama streaming request failed: {exc}") from exc

    try:
        for line in resp.iter_lines():
            if line:
                try:
                    chunk = json.loads(
                        line.decode("utf-8") if isinstance(line, bytes) else line
                    )
                except ValueError as exc:
                    raise OllamaInferenceError(
                        "Ollama returned a malformed streaming chunk"
                    ) from exc

                if chunk.get("error"):
                    raise OllamaInferenceError(f"Ollama error: {chunk['error']}")

                token = chunk.get("response", "")

                if token:
                    full_answer.append(token)
                    filtered = think_filter.filter_token(token)
                    if filtered:
                        yield filtered

                if chunk.get("done", False):
                    eval_count = chunk.get(
                        "eval_count",
                        len("".join(full_answer).split()),
                    )
                    prompt_eval_count = chunk.get(
                        "prompt_eval_count",
                        0,
                    )
                    break
    except requests.RequestException as exc:
        raise OllamaInferenceError(f"Ollama stream interrupted: {exc}") from exc
    finally:
        # Also runs when the consumer abandons the generator (client disconnect),
        # releasing the HTTP connection to Ollama.
        resp.close()

    # The held-back tail is already in full_answer (raw tokens); only the
    # stream still needs it.
    flushed = think_filter.flush()
    if flushed:
        yield flushed

    cleaned_answer = strip_thinking_tags("".join(full_answer))
    return (
        cleaned_answer,
        eval_count,
        prompt_eval_count,
    )


