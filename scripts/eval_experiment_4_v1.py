def render_gfm_table(
    headers: List[str],
    rows: List[List[str]],
    caption: str = "",
    block_id: int = 0,
    max_tokens: int = MAX_TABLE_TOKENS,
) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """
    Convert an HTML table grid into contiguous GFM Markdown chunks under max_tokens budget.
    Preserves:
    - Caption / title
    - Headers and header column alignments
    - Row order and exact 0-indexed row mapping
    - Escapes literal pipes and normalizes whitespace
    - Pads uneven rows to maximum table column width
    """
    clean_headers = [html.unescape(h).replace("|", "\\|").strip() for h in headers]
    clean_rows: List[List[str]] = []
    for r in rows:
        clean_rows.append([html.unescape(c).replace("|", "\\|").replace("\n", " ").strip() for c in r])

    max_cols = max([len(clean_headers)] + [len(r) for r in clean_rows]) if (clean_rows or clean_headers) else 1

    header_status = "PRESERVED_EXPLICIT"
    if len(clean_headers) == 1 and max_cols > 1:
        # Title banner row in Wikipedia infoboxes
        table_title = clean_headers[0] if not caption else caption
        caption = table_title
        header_status = "TITLE_BANNER_TO_CAPTION"
        if max_cols == 2:
            clean_headers = ["Property", "Value"]
        else:
            clean_headers = [f"Col_{i+1}" for i in range(max_cols)]
    elif not clean_headers or all(h.startswith("Col_") for h in clean_headers):
        header_status = "GENERATED_DEFAULT"
        clean_headers = [f"Col_{i+1}" for i in range(max_cols)]
    else:
        while len(clean_headers) < max_cols:
            clean_headers.append(f"Col_{len(clean_headers)+1}")

    hdr_line = "| Row | " + " | ".join(clean_headers) + " |"
    sep_line = "| --- | " + " | ".join(["---"] * len(clean_headers)) + " |"

    chunks: List[Dict[str, Any]] = []
    curr_chunk_rows: List[str] = []
    start_r = 0

    title_str = f"### Table {block_id}" + (f": {caption}" if caption else "")

    for r_idx, r in enumerate(clean_rows):
        padded_r = r + [""] * (max_cols - len(r))
        row_line = f"| {r_idx} | " + " | ".join(padded_r) + " |"

        test_lines = [title_str + f" [Rows {start_r}-{r_idx}]", hdr_line, sep_line] + curr_chunk_rows + [row_line]
        if estimate_text_tokens("\n".join(test_lines)) > max_tokens and curr_chunk_rows:
            chunk_header = title_str + f" [Rows {start_r}-{r_idx-1}]"
            chunk_lines = [chunk_header, hdr_line, sep_line] + curr_chunk_rows
            chunk_text = "\n".join(chunk_lines)
            chunk_toks = estimate_text_tokens(chunk_text)
            chunks.append({
                "chunk_idx": len(chunks),
                "start_row": start_r,
                "end_row": r_idx - 1,
                "row_count": len(curr_chunk_rows),
                "estimated_tokens": chunk_toks,
                "text": chunk_text,
                "row_indices": list(range(start_r, r_idx)),
            })
            start_r = r_idx
            curr_chunk_rows = [row_line]
        else:
            curr_chunk_rows.append(row_line)

    if curr_chunk_rows:
        chunk_header = title_str + f" [Rows {start_r}-{len(clean_rows)-1}]"
        chunk_lines = [chunk_header, hdr_line, sep_line] + curr_chunk_rows
        chunk_text = "\n".join(chunk_lines)
        chunk_toks = estimate_text_tokens(chunk_text)
        chunks.append({
            "chunk_idx": len(chunks),
            "start_row": start_r,
            "end_row": len(clean_rows) - 1,
            "row_count": len(curr_chunk_rows),
            "estimated_tokens": chunk_toks,
            "text": chunk_text,
            "row_indices": list(range(start_r, len(clean_rows))),
        })

    meta = {
        "block_id": block_id,
        "caption": caption,
        "headers": clean_headers,
        "header_status": header_status,
        "original_row_count": len(rows),
        "rendered_row_count": sum(c["row_count"] for c in chunks),
        "max_cols": max_cols,
        "total_chunks": len(chunks),
        "total_tokens": sum(c["estimated_tokens"] for c in chunks),
        "chunk_boundaries": [
            {
                "chunk_idx": c["chunk_idx"],
                "start_row": c["start_row"],
                "end_row": c["end_row"],
                "tokens": c["estimated_tokens"],
            }
            for c in chunks
        ],
    }
    return chunks, meta


def render_list_items(block: StructuredBlock) -> Tuple[str, int]:
    """Preserve raw list item text, item order, and source location."""
    lines = [f"### List {block.block_id}:"]
    for idx, r in enumerate(block.rows):
        if r:
            lines.append(f"- [Item {idx}]: {html.unescape(r[0]).strip()}")
    text = "\n".join(lines)
    tokens = estimate_text_tokens(text)
    return text, tokens


def build_structural_retention_context(
    raw_doc: str,
    query: str,
    table_threshold: float = TABLE_SELECTION_THRESHOLD,
    include_lists: bool = False,
    max_table_tokens: int = MAX_TABLE_TOKENS,
    token_ceiling: int = DEFAULT_TOKEN_CEILING,
) -> Tuple[str, StructuralRetentionTelemetry]:
    """
    Construct packed prompt context from raw HTML document using structural evidence retention.
    Logs each stage separately:
    1. Conversion: HTML tables -> GFM Markdown tables with headers preserved.
    2. Selection: Query-aware table scoring using score_and_select_tables().
    3. Row Retention: 100% row preservation policy within selected tables (vs Stage C top-5).
    4. Chunking: 500-token per-table cap with contiguous row chunking.
    5. Packing: Packing clean prose + selected table chunks + optional raw lists up to token_ceiling.
    """
    parser = StructuralDocumentParser(raw_doc)
    clean_prose, blocks = parser.parse()

    tbl_blocks = [b for b in blocks if b.block_type == "table"]
    list_blocks = [b for b in blocks if b.block_type in ("ordered_list", "unordered_list")]

    telemetry = StructuralRetentionTelemetry()

    # Stage 1: Conversion
    rendered_tables: Dict[int, Tuple[List[Dict[str, Any]], Dict[str, Any]]] = {}
    for b in tbl_blocks:
        try:
            chunks, meta = render_gfm_table(
                headers=b.headers,
                rows=b.rows,
                caption=b.caption,
                block_id=b.block_id,
                max_tokens=max_table_tokens,
            )
            rendered_tables[b.block_id] = (chunks, meta)
            telemetry.conversion.append({
                "source_block_id": b.block_id,
                "caption": b.caption,
                "original_headers": b.headers,
                "rendered_headers": meta["headers"],
                "header_preservation_status": meta["header_status"],
                "original_row_count": meta["original_row_count"],
                "rendered_row_count": meta["rendered_row_count"],
                "row_preservation_rate": 1.0 if meta["original_row_count"] == meta["rendered_row_count"] else round(meta["rendered_row_count"] / max(1, meta["original_row_count"]), 4),
                "conversion_status": "SUCCESS",
            })
        except Exception as exc:
            telemetry.conversion.append({
                "source_block_id": b.block_id,
                "caption": b.caption,
                "original_headers": b.headers,
                "rendered_headers": [],
                "header_preservation_status": "FAILED",
                "original_row_count": len(b.rows),
                "rendered_row_count": 0,
                "row_preservation_rate": 0.0,
                "conversion_status": f"FAILURE: {exc}",
            })

    # Stage 2: Selection
    parsed_tables: List[ParsedTable] = []
    for b in tbl_blocks:
        p_rows: List[ParsedTableRow] = []
        for r_idx, r in enumerate(b.rows):
            cells = [ParsedTableCell(tag="td", text=c) for c in r]
            p_rows.append(ParsedTableRow(row_idx=r_idx, raw_html="", cells=cells))
        headers = b.headers if b.headers else [f"Col_{i}" for i in range(len(b.rows[0]))] if b.rows else []
        parsed_tables.append(ParsedTable(
            table_idx=b.block_id,
            caption=b.caption,
            headers=headers,
            rows=p_rows,
            raw_html="",
        ))

    scored_tables = score_and_select_tables(parsed_tables, query, raw_doc) if parsed_tables else []
    selected_tbl_ids: Set[int] = set()

    for table, score, decision, _ in scored_tables:
        is_selected = decision.startswith("SELECTED") and (score >= table_threshold or "infobox" in decision.lower())
        if is_selected:
            selected_tbl_ids.add(table.table_idx)
        telemetry.selection.append({
            "block_id": table.table_idx,
            "score": score,
            "decision": decision if is_selected else f"REJECTED: below threshold {table_threshold}",
            "threshold": table_threshold,
        })

    # Stage 3: Row Retention (100% row preservation within selected tables)
    for b in tbl_blocks:
        if b.block_id in selected_tbl_ids:
            telemetry.row_retention.append({
                "block_id": b.block_id,
                "original_rows": len(b.rows),
                "retained_rows": len(b.rows),
                "row_retention_rate": 1.0,
                "policy": "retain_all_rows_gfm_chunking",
            })

    # Stage 4: Chunking
    for b_id in selected_tbl_ids:
        if b_id in rendered_tables:
            chunks, _ = rendered_tables[b_id]
            for ch in chunks:
                telemetry.chunking.append({
                    "block_id": b_id,
                    "chunk_idx": ch["chunk_idx"],
                    "start_row": ch["start_row"],
                    "end_row": ch["end_row"],
                    "row_count": ch["row_count"],
                    "estimated_tokens": ch["estimated_tokens"],
                })

    # Stage 5: Context Assembly & Packing
    clean_prose_str = clean_prose.strip()
    clean_prose_tokens = estimate_text_tokens(clean_prose_str) if clean_prose_str else 0

    packed_parts: List[str] = []
    cur_tokens = 0
    table_chunks_packed = 0
    table_tokens_packed = 0

    if clean_prose_str and clean_prose_tokens > 0:
        packed_parts.append(f"### Clean Prose:\n{clean_prose_str}")
        cur_tokens += clean_prose_tokens

    # Pack selected tables sorted by score descending
    sorted_tables = sorted(
        [t for t in scored_tables if t[0].table_idx in selected_tbl_ids],
        key=lambda x: x[1],
        reverse=True,
    )

    for t_item in sorted_tables:
        t_idx = t_item[0].table_idx
        if t_idx in rendered_tables:
            chunks, _ = rendered_tables[t_idx]
            for ch in chunks:
                if cur_tokens + ch["estimated_tokens"] <= token_ceiling:
                    packed_parts.append(ch["text"])
                    cur_tokens += ch["estimated_tokens"]
                    table_chunks_packed += 1
                    table_tokens_packed += ch["estimated_tokens"]

    # Append list items if Condition D
    list_items_packed = 0
    list_tokens_packed = 0
    if include_lists:
        for lb in list_blocks:
            l_text, l_tok = render_list_items(lb)
            if cur_tokens + l_tok <= token_ceiling:
                packed_parts.append(l_text)
                cur_tokens += l_tok
                list_items_packed += len(lb.rows)
                list_tokens_packed += l_tok

    full_context = "\n\n".join(packed_parts)

    telemetry.packing = {
        "clean_prose_estimated_tokens": clean_prose_tokens,
        "table_chunks_packed_count": table_chunks_packed,
        "table_chunks_estimated_tokens": table_tokens_packed,
        "list_items_packed_count": list_items_packed,
        "list_estimated_tokens": list_tokens_packed,
        "total_context_estimated_tokens": cur_tokens,
        "ceiling_violation": cur_tokens > token_ceiling,
        "zero_context": len(full_context.strip()) == 0,
    }

    return full_context, telemetry


