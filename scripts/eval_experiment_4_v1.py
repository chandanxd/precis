@dataclass
class ConditionResult:
    """
    Record schema for individual experimental condition prediction.
    Gate 2.1 Failure-Handling Correction:
    - Status distinguishes: 'success', 'failed', 'unscorable', 'dry_run'.
    - exact_match, containment, and rouge_l are strictly None when status != 'success'.
    - full_prompt_model_tokens represents the complete prompt token count from Ollama (prompt_eval_count).
    - context_estimated_tokens represents the heuristic subword token estimate of context alone.
    """
    condition_id: str
    predicted_answer: Optional[str] = None
    raw_response: Optional[str] = None
    exact_match: Optional[bool] = None
    containment: Optional[bool] = None
    rouge_l: Optional[float] = None
    context_estimated_tokens: int = 0
    full_prompt_model_tokens: Optional[int] = None
    generated_tokens: int = 0
    latency_ms: int = 0
    status: Literal["success", "failed", "unscorable", "dry_run"] = "success"
    error_message: Optional[str] = None
    provenance: Dict[str, Any] = field(default_factory=dict)
    structural_retention_telemetry: Optional[Dict[str, Any]] = None


def validate_condition_result(res: Dict[str, Any]) -> None:
    """
    Validate condition result schema integrity and reject contradictory status/score states.
    - 'failed', 'unscorable', 'dry_run' MUST have exact_match=None, containment=None, rouge_l=None.
    - 'success' MUST have non-null boolean exact_match, non-null boolean containment, non-null float rouge_l.
    - status must be one of the recognized literals.
    """
    status = res.get("status")
    valid_statuses = ("success", "failed", "unscorable", "dry_run")
    if status not in valid_statuses:
        raise ValueError(f"Invalid condition status '{status}'; must be one of {valid_statuses}")

    em = res.get("exact_match")
    cont = res.get("containment")
    rouge = res.get("rouge_l")

    if status in ("failed", "unscorable", "dry_run"):
        if em is not None or cont is not None or rouge is not None:
            raise ValueError(
                f"Contradictory state: status='{status}' cannot have scored metrics. "
                f"Found exact_match={em}, containment={cont}, rouge_l={rouge}."
            )
    elif status == "success":
        if em is None or cont is None or rouge is None:
            raise ValueError(
                f"Contradictory state: status='success' must have scored metrics. "
                f"Found exact_match={em}, containment={cont}, rouge_l={rouge}."
            )
        if not isinstance(em, bool) or not isinstance(cont, bool):
            raise ValueError(
                f"Type error: status='success' requires boolean exact_match and containment, "
                f"got exact_match={type(em)}, containment={type(cont)}."
            )
        if not isinstance(rouge, (int, float)):
            raise ValueError(f"Type error: rouge_l must be numeric, got {type(rouge)}.")
        if not isinstance(res.get("predicted_answer"), str):
            raise ValueError("status='success' requires string predicted_answer.")


@dataclass
class Experiment4CaseRecord:
    """Unified paired case record for Experiment 4 across Conditions A, B, C, D."""
    case_id: str
    question: str
    gold_answer: str
    answers: List[str]
    stratum: str
    priority_cohort: str  # P1_regression | P2_recovery | other
    cond_a: Dict[str, Any]
    cond_b: Dict[str, Any]
    cond_c: Optional[Dict[str, Any]] = None
    cond_d: Optional[Dict[str, Any]] = None
    c_vs_a: Optional[Dict[str, Any]] = None
    c_vs_b: Optional[Dict[str, Any]] = None
    d_vs_a: Optional[Dict[str, Any]] = None
    d_vs_b: Optional[Dict[str, Any]] = None
    d_vs_c: Optional[Dict[str, Any]] = None


def validate_case_record(record: Experiment4CaseRecord | Dict[str, Any]) -> None:
    """Validate all condition sections in an Experiment 4 case record."""
    d = asdict(record) if isinstance(record, Experiment4CaseRecord) else record
    for cond_key in ("cond_a", "cond_b", "cond_c", "cond_d"):
        c_val = d.get(cond_key)
        if c_val is not None:
            validate_condition_result(c_val)


