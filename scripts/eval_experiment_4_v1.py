def compute_condition_summary(
    records: List[Experiment4CaseRecord],
    cond_key: str,
) -> Dict[str, Any]:
    """
    Compute condition-level summary with explicit denominators and failure transparency.
    Reports cases attempted, success, failed, unscorable counts.
    Never imputes failures as incorrect answers.
    Returns None for accuracy metrics if scored_denominator == 0.
    """
    total_attempted = len(records)
    cond_objs = [getattr(r, cond_key) for r in records]

    success_objs = [c for c in cond_objs if c["status"] == "success"]
    failed_objs = [c for c in cond_objs if c["status"] == "failed"]
    unscorable_objs = [c for c in cond_objs if c["status"] == "unscorable"]
    dry_run_objs = [c for c in cond_objs if c["status"] == "dry_run"]

    success_cnt = len(success_objs)
    failed_cnt = len(failed_objs)
    unscorable_cnt = len(unscorable_objs)
    dry_run_cnt = len(dry_run_objs)

    failed_ids = [r.case_id for r, c in zip(records, cond_objs) if c["status"] == "failed"]
    unscorable_ids = [r.case_id for r, c in zip(records, cond_objs) if c["status"] == "unscorable"]

    if success_cnt > 0:
        em_cnt = sum(1 for c in success_objs if c["exact_match"] is True)
        em_rate = em_cnt / success_cnt
        cont_cnt = sum(1 for c in success_objs if c["containment"] is True)
        cont_rate = cont_cnt / success_cnt
        rouge_mean = sum(c["rouge_l"] for c in success_objs) / success_cnt
        status_summary = "completed"
    else:
        em_cnt = None
        em_rate = None
        cont_cnt = None
        cont_rate = None
        rouge_mean = None
        status_summary = "dry_run" if dry_run_cnt > 0 else "unavailable"

    mean_ctx_tokens = sum(c["context_estimated_tokens"] for c in cond_objs) / max(1, total_attempted)
    valid_prompt_tokens = [c["full_prompt_model_tokens"] for c in cond_objs if c.get("full_prompt_model_tokens") is not None]
    mean_prompt_tokens = (sum(valid_prompt_tokens) / len(valid_prompt_tokens)) if valid_prompt_tokens else None
    valid_gen_tokens = [c["generated_tokens"] for c in success_objs]
    mean_gen_tokens = (sum(valid_gen_tokens) / len(valid_gen_tokens)) if valid_gen_tokens else None

    return {
        "status": status_summary,
        "attempted_count": total_attempted,
        "success_count": success_cnt,
        "failed_count": failed_cnt,
        "unscorable_count": unscorable_cnt,
        "dry_run_count": dry_run_cnt,
        "scored_denominator": success_cnt,
        "exact_match_count": em_cnt,
        "exact_match_rate": em_rate,
        "containment_count": cont_cnt,
        "containment_rate": cont_rate,
        "mean_rouge_l": rouge_mean,
        "mean_context_estimated_tokens": mean_ctx_tokens,
        "mean_full_prompt_model_tokens": mean_prompt_tokens,
        "mean_generated_tokens": mean_gen_tokens,
        "unsuccessful_case_ids": {
            "failed": failed_ids,
            "unscorable": unscorable_ids,
        },
    }


def compute_paired_comparison_summary(
    records: List[Experiment4CaseRecord],
    cond1_key: str,
    cond2_key: str,
    metric: str = "exact_match",
) -> Dict[str, Any]:
    """
    Compute paired comparison summary excluding cases where either condition failed or is unscorable.
    Explicitly tracks:
    - attempted_pair_count
    - valid_paired_denominator
    - evaluated_case_ids
    - excluded_count, excluded_case_ids, exclusion_details
    - McNemar exact test strictly on valid pairs.
    """
    total_attempted = len(records)
    included_case_ids = []
    excluded_case_ids = []
    exclusion_details = []
    y1_vals: List[bool] = []
    y2_vals: List[bool] = []

    for r in records:
        c1 = getattr(r, cond1_key)
        c2 = getattr(r, cond2_key)

        is_valid_c1 = (c1.get("status") == "success" and c1.get(metric) is not None)
        is_valid_c2 = (c2.get("status") == "success" and c2.get(metric) is not None)

        if is_valid_c1 and is_valid_c2:
            included_case_ids.append(r.case_id)
            y1_vals.append(bool(c1[metric]))
            y2_vals.append(bool(c2[metric]))
        else:
            excluded_case_ids.append(r.case_id)
            reasons = []
            if not is_valid_c1:
                reasons.append(f"{cond1_key} status='{c1.get('status')}' ({c1.get('error_message') or 'no valid score'})")
            if not is_valid_c2:
                reasons.append(f"{cond2_key} status='{c2.get('status')}' ({c2.get('error_message') or 'no valid score'})")
            exclusion_details.append({
                "case_id": r.case_id,
                "reason": "; ".join(reasons),
            })

    valid_denom = len(included_case_ids)
    if valid_denom == 0:
        return {
            "status": "unavailable",
            "attempted_pair_count": total_attempted,
            "valid_paired_denominator": 0,
            "evaluated_case_ids": [],
            "excluded_count": len(excluded_case_ids),
            "excluded_case_ids": excluded_case_ids,
            "exclusion_details": exclusion_details,
            "mcnemar_exact": None,
            "notes": "No valid pairs with successful scores for both conditions; metrics unavailable.",
        }

    mcnemar_res = compute_mcnemar_exact(y1_vals, y2_vals)
    return {
        "status": "computed",
        "attempted_pair_count": total_attempted,
        "valid_paired_denominator": valid_denom,
        "evaluated_case_ids": included_case_ids,
        "excluded_count": len(excluded_case_ids),
        "excluded_case_ids": excluded_case_ids,
        "exclusion_details": exclusion_details,
        "mcnemar_exact": mcnemar_res,
    }


def make_paired_case_diff(c1: Dict[str, Any], c2: Dict[str, Any]) -> Dict[str, Any]:
    """Calculate case-level paired difference; marks status='excluded' if either condition is not success."""
    if (c1.get("status") == "success" and c2.get("status") == "success" and
            c1.get("exact_match") is not None and c2.get("exact_match") is not None):
        return {
            "status": "valid",
            "em_win": bool(c1["exact_match"] and not c2["exact_match"]),
            "em_loss": bool(not c1["exact_match"] and c2["exact_match"]),
            "containment_win": bool(c1["containment"] and not c2["containment"]),
            "containment_loss": bool(not c1["containment"] and c2["containment"]),
            "token_delta": c1["context_estimated_tokens"] - c2["context_estimated_tokens"],
        }
    else:
        reasons = []
        if c1.get("status") != "success":
            reasons.append(f"cond1 status='{c1.get('status')}'")
        if c2.get("status") != "success":
            reasons.append(f"cond2 status='{c2.get('status')}'")
        return {
            "status": "excluded",
            "reason": "; ".join(reasons) or "incomplete scores",
            "em_win": None,
            "em_loss": None,
            "containment_win": None,
            "containment_loss": None,
            "token_delta": None,
        }


