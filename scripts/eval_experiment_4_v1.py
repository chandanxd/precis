# ==============================================================================

def compute_mcnemar_exact(
    y_true_1: List[bool],
    y_true_2: List[bool],
) -> Dict[str, Any]:
    """
    Compute McNemar's exact test for paired binary evaluation outcomes.
    Operates strictly over paired cases where both conditions produced valid, scored predictions.
    Contingency table:
    - a: both Condition 1 and Condition 2 are True (concordant positive)
    - b: Condition 1 is True, Condition 2 is False (Condition 1 win)
    - c: Condition 1 is False, Condition 2 is True (Condition 2 win)
    - d: both Condition 1 and Condition 2 are False (concordant negative)
    Discordant pairs: n_disc = b + c.
    Under H0, discordant pairs follow Binomial(n=b+c, p=0.5).
    Handles edge cases:
    - Zero discordant pairs (b=0, c=0): p = 1.0, odds ratio = 1.0, risk difference = 0.0.
    - All discordant pairs (symmetric or asymmetric).
    """
    if len(y_true_1) != len(y_true_2):
        raise ValueError(f"Mismatched sample lengths: {len(y_true_1)} vs {len(y_true_2)}")

    n = len(y_true_1)
    if n == 0:
        return {
            "status": "unavailable",
            "total_n": 0,
            "contingency_table": {"a_both_positive": 0, "b_cond1_pos_cond2_neg": 0, "c_cond1_neg_cond2_pos": 0, "d_both_negative": 0},
            "discordant_pairs": 0,
            "cond1_wins": 0,
            "cond2_wins": 0,
            "net_wins_cond1": 0,
            "risk_difference": None,
            "odds_ratio": None,
            "p_value": None,
            "statistically_significant_05": False,
        }

    a = sum(1 for y1, y2 in zip(y_true_1, y_true_2) if y1 and y2)
    b = sum(1 for y1, y2 in zip(y_true_1, y_true_2) if y1 and not y2)
    c = sum(1 for y1, y2 in zip(y_true_1, y_true_2) if not y1 and y2)
    d = sum(1 for y1, y2 in zip(y_true_1, y_true_2) if not y1 and not y2)

    n_disc = b + c
    if n_disc == 0:
        p_val = 1.0
        odds_ratio = 1.0
    else:
        # Exact two-sided binomial test
        res = scipy.stats.binomtest(b, n=n_disc, p=0.5, alternative="two-sided")
        p_val = float(res.pvalue)
        odds_ratio = float(b / c) if c > 0 else (float("inf") if b > 0 else 1.0)

    risk_difference = (b - c) / n if n > 0 else 0.0

    return {
        "status": "computed",
        "total_n": n,
        "contingency_table": {
            "a_both_positive": a,
            "b_cond1_pos_cond2_neg": b,
            "c_cond1_neg_cond2_pos": c,
            "d_both_negative": d,
        },
        "discordant_pairs": n_disc,
        "cond1_wins": b,
        "cond2_wins": c,
        "net_wins_cond1": b - c,
        "risk_difference": risk_difference,
        "odds_ratio": odds_ratio,
        "p_value": p_val,
        "statistically_significant_05": p_val < 0.05 if p_val is not None else False,
    }


