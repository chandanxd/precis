def validate_cohort_membership(
    manifest_records: List[Dict[str, Any]],
    stage_c_records: Dict[str, Dict[str, Any]],
) -> Tuple[List[str], List[str], List[str]]:
    """
    Reconstruct the targeted 58-case unique diagnostic union from manifest and Stage C records.
    Validates:
    - Confirmatory stratum contains exactly 200 cases.
    - Exactly 47 Stage C regressions (Cond A = 1, Cond B = 0).
    - Exactly 11 Stage C recoveries (Cond A = 0, Cond B = 1).
    - Regressions and recoveries are strictly disjoint (intersection = 0).
    - Union contains exactly 58 unique cases.
    - Zero duplicate, missing, or unexpected case IDs.
    """
    confirmatory_cases = [
        m for m in manifest_records
        if m.get("type") == "sample_record" and m.get("stratum") == "table_bearing"
    ]
    if len(confirmatory_cases) != 200:
        raise ValueError(f"Cohort validation failed: expected 200 table_bearing cases, found {len(confirmatory_cases)}")

    regressions: List[str] = []
    recoveries: List[str] = []

    for m in confirmatory_cases:
        cid = m["sample_id"]
        if cid not in stage_c_records:
            raise KeyError(f"Missing case ID in Stage C records: {cid}")
        rec = stage_c_records[cid]
        cond_a = rec.get("cond_a", {})
        cond_b = rec.get("cond_b", {})

        if cond_a.get("status") != "success" or cond_b.get("status") != "success":
            raise ValueError(f"Case {cid} has non-success status in frozen Stage C records: A={cond_a.get('status')}, B={cond_b.get('status')}")

        em_a = bool(cond_a.get("exact_match", False))
        em_b = bool(cond_b.get("exact_match", False))

        if em_a and not em_b:
            regressions.append(cid)
        elif not em_a and em_b:
            recoveries.append(cid)

    if len(regressions) != 47:
        raise ValueError(f"Expected 47 Stage C regressions, found {len(regressions)}")
    if len(recoveries) != 11:
        raise ValueError(f"Expected 11 Stage C recoveries, found {len(recoveries)}")

    intersection = set(regressions) & set(recoveries)
    if len(intersection) != 0:
        raise ValueError(f"Cohort validation failed: non-empty intersection between regressions and recoveries: {intersection}")

    union_cases = sorted(list(set(regressions) | set(recoveries)))
    if len(union_cases) != 58:
        raise ValueError(f"Expected 58 cases in unique union, found {len(union_cases)}")

    return regressions, recoveries, union_cases


def load_frozen_baseline_records(
    stage_c_path: Path,
    target_case_ids: Set[str],
) -> Dict[str, Dict[str, Any]]:
    """
    Load frozen Condition A and Condition B predictions and metrics from Stage C records.
    Attaches provenance metadata and validates explicit status tags.
    """
    if not stage_c_path.exists():
        raise FileNotFoundError(f"Stage C records file missing: {stage_c_path}")

    records: Dict[str, Dict[str, Any]] = {}
    with open(stage_c_path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            r = json.loads(line)
            if r.get("type") == "sample_record":
                sid = r["sample_id"]
                if sid in target_case_ids:
                    records[sid] = r

    missing = target_case_ids - set(records.keys())
    if missing:
        raise KeyError(f"Failed to load frozen baselines for {len(missing)} cases: {missing}")

    return records


